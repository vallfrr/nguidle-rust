"""Inventory of the game's screens / interactive elements, generated from out/ngu/scene.json. Output: local/docs/SCREEN-INVENTORY.md (not published: game texts)"""
import json, collections, re
d = json.load(open(r"J:\NGUvita\nguvita\out\ngu\scene.json", encoding="utf-8")); O = d["objects"]
rt = {k: v for k, v in O.items() if v["t"] == "RectTransform"}
def go(k): return O[O[k]["d"]["m_GameObject"]]
def comps(g):
    for c in g["d"]["m_Component"]:
        o = O.get(c["component"])
        if o: yield o
def texts(k, out, depth=0):
    for o in comps(go(k)):
        if o["t"] == "MonoBehaviour" and o.get("script") and o["script"]["cls"] == "Text":
            t = re.sub(r"<[^>]+>", "", o["d"].get("m_Text", "")).replace("\n", " ").strip()
            if t: out.append(t)
    for ch in rt[k]["d"]["m_Children"]:
        if ch in rt and depth < 3: texts(ch, out, depth + 1)
def label(k):
    out = []; texts(k, out)
    return (out[0][:28] if out else "") or go(k)["d"]["m_Name"][:28]
def walk(k, acc):
    g = go(k)
    for o in comps(g):
        if o["t"] != "MonoBehaviour" or not o.get("script"): continue
        c = o["script"]["cls"]; dd = o["d"]
        if c == "Button":
            calls = [x["m_MethodName"] for x in dd["m_OnClick"]["m_PersistentCalls"]["m_Calls"]]
            acc["btn"].append((label(k), ",".join(calls) or "(script)"))
        elif c == "EventTrigger": acc["trig"].append(label(k))
        elif c == "Slider": acc["sld"].append(label(k))
        elif c == "InputField": acc["inp"].append(go(k)["d"]["m_Name"][:24])
        elif c == "ScrollRect": acc["scr"].append(go(k)["d"]["m_Name"][:24])
        elif c == "Toggle": acc["tog"].append(label(k))
        elif c not in ("Image", "Text", "Mask", "Outline", "CanvasScaler", "GraphicRaycaster", "Scrollbar", "GridLayoutGroup", "VerticalLayoutGroup", "ContentSizeFitter"):
            acc["scripts"][c] += 1
    for ch in rt[k]["d"]["m_Children"]:
        if ch in rt: walk(ch, acc)
cv = [k for k, v in rt.items() if v["d"]["m_Father"] is None and go(k)["d"]["m_Name"] == "Canvas"][0]
lines = ["# Screen inventory (generated by tools/inventory.py)\n",
         "Source: the game's scene (hierarchy, components, button calls). `btn` = Button (label -> game method), `trig` = hover/drag (EventTrigger), `sld` = sliders, `inp` = input fields, `scr` = scroll areas.\n"]
tot = collections.Counter()
for k in rt[cv]["d"]["m_Children"]:
    if k not in rt: continue
    g = go(k); name = g["d"]["m_Name"]
    if re.match(r"(Middle Bolt|End Panel|Big Menu Backup|Backup Small)", name): continue
    acc = {"btn": [], "trig": [], "sld": [], "inp": [], "scr": [], "tog": [], "scripts": collections.Counter()}
    walk(k, acc)
    a = rt[k]["d"]; sx = a["m_SizeDelta"]
    lines.append(f"\n## {name}  ({sx['x']:.0f}x{sx['y']:.0f}, ancrage {a['m_AnchorMin']['x']:.0f},{a['m_AnchorMin']['y']:.0f}-{a['m_AnchorMax']['x']:.0f},{a['m_AnchorMax']['y']:.0f})")
    lines.append(f"btn {len(acc['btn'])} | trig {len(acc['trig'])} | sld {len(acc['sld'])} | inp {len(acc['inp'])} | scr {len(acc['scr'])} | tog {len(acc['tog'])}")
    for n in ("btn", "trig", "sld", "inp", "scr", "tog"): tot[n] += len(acc[n])
    if acc["btn"]: lines.append("- buttons: " + "; ".join(f"{l} -> {m}" for l, m in acc["btn"][:14]) + (" ..." if len(acc["btn"]) > 14 else ""))
    if acc["inp"]: lines.append("- inputs: " + ", ".join(acc["inp"][:8]))
    if acc["scr"]: lines.append("- scrolling: " + ", ".join(acc["scr"][:6]))
    if acc["scripts"]: lines.append("- game scripts: " + ", ".join(f"{c}x{n}" for c, n in acc["scripts"].most_common(10)))
lines.insert(2, f"Totaux : {dict(tot)}\n")
__import__("os").makedirs("local/docs", exist_ok=True)
open("local/docs/SCREEN-INVENTORY.md", "w", encoding="utf-8").write("\n".join(lines))
print("ok", dict(tot), len(lines))
